// @vitest-environment node
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';

const migration = readFileSync(new URL('../../supabase/migrations/20261108082331_schedule_company_news.sql', import.meta.url), 'utf8');
const gatewayMigration = readFileSync(new URL('../../supabase/migrations/20261108083056_company_news_gateway_auth.sql', import.meta.url), 'utf8');

describe('company news scheduler migration', () => {
  let db: PGlite;

  beforeAll(async () => {
    db = new PGlite();
    // Exercise the migration's actual SQL and scheduled statement while replacing
    // network/extension implementations with local state, never remote services.
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated;
      CREATE SCHEMA vault;
      CREATE TABLE vault.secrets (
        id uuid PRIMARY KEY DEFAULT gen_random_uuid(), name text UNIQUE, secret text, description text
      );
      CREATE VIEW vault.decrypted_secrets AS
        SELECT id, name, secret AS decrypted_secret, description FROM vault.secrets;
      CREATE FUNCTION vault.create_secret(_secret text, _name text, _description text)
      RETURNS uuid LANGUAGE sql AS $$
        INSERT INTO vault.secrets (secret, name, description) VALUES (_secret, _name, _description) RETURNING id
      $$;
      CREATE SCHEMA cron;
      CREATE TABLE cron.job (
        jobid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        jobname text UNIQUE NOT NULL, schedule text NOT NULL, command text NOT NULL,
        active boolean NOT NULL DEFAULT true
      );
      CREATE FUNCTION cron.schedule(_name text, _schedule text, _command text)
      RETURNS bigint LANGUAGE sql AS $$
        INSERT INTO cron.job (jobname, schedule, command) VALUES (_name, _schedule, _command)
        ON CONFLICT (jobname) DO UPDATE SET schedule = excluded.schedule, command = excluded.command
        RETURNING jobid
      $$;
      CREATE FUNCTION cron.alter_job(job_id bigint, active boolean DEFAULT NULL)
      RETURNS void LANGUAGE sql AS $$
        UPDATE cron.job SET active = coalesce(alter_job.active, cron.job.active) WHERE jobid = job_id
      $$;
      CREATE SCHEMA net;
      CREATE TABLE net.requests (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        url text, headers jsonb, body jsonb, timeout_milliseconds integer
      );
      CREATE FUNCTION net.http_post(url text, headers jsonb, body jsonb, timeout_milliseconds integer)
      RETURNS bigint LANGUAGE sql AS $$
        INSERT INTO net.requests (url, headers, body, timeout_milliseconds)
        VALUES (url, headers, body, timeout_milliseconds) RETURNING id
      $$;
      REVOKE ALL ON SCHEMA vault FROM PUBLIC, anon, authenticated;
      REVOKE ALL ON vault.secrets, vault.decrypted_secrets FROM PUBLIC, anon, authenticated;
    `);
  }, 30_000);

  beforeEach(async () => {
    await db.exec('RESET ROLE');
    await db.exec(`TRUNCATE vault.secrets, cron.job, net.requests RESTART IDENTITY;
      INSERT INTO cron.job (jobname, schedule, command)
      VALUES ('daily-report-cleanup', '0 3 * * *', 'SELECT 1');`);
  });
  afterAll(async () => { await db?.close(); });

  it('creates a random private credential and only its own hourly job', async () => {
    await db.exec(migration);
    const secrets = (await db.query<{ name: string; decrypted_secret: string }>('SELECT name, decrypted_secret FROM vault.decrypted_secrets')).rows;
    expect(secrets).toHaveLength(1);
    expect(secrets[0].name).toBe('company_news_cron_token');
    expect(secrets[0].decrypted_secret).toMatch(/^[a-f0-9]{64}$/);
    const jobs = (await db.query<{ jobname: string; schedule: string; command: string }>('SELECT jobname, schedule, command FROM cron.job ORDER BY jobname')).rows;
    expect(jobs).toHaveLength(2);
    expect(jobs[0]).toMatchObject({ jobname: 'company-news-hourly', schedule: '17 * * * *' });
    expect(jobs[0].command).not.toContain(secrets[0].decrypted_secret);
    expect(jobs[1]).toEqual({ jobname: 'daily-report-cleanup', schedule: '0 3 * * *', command: 'SELECT 1' });
  });

  it('is idempotent, retains the same credential and job identity, and leaves unrelated jobs untouched', async () => {
    await db.exec(migration);
    const before = (await db.query('SELECT id, name, secret FROM vault.secrets')).rows;
    const jobsBefore = (await db.query('SELECT * FROM cron.job ORDER BY jobid')).rows;
    await db.exec(migration);
    expect((await db.query('SELECT id, name, secret FROM vault.secrets')).rows).toEqual(before);
    expect((await db.query('SELECT * FROM cron.job ORDER BY jobid')).rows).toEqual(jobsBefore);
  });

  it('reuses an existing scheduler credential and updates only its named schedule', async () => {
    await db.query('INSERT INTO vault.secrets (name, secret) VALUES ($1, $2)', ['company_news_cron_token', 'existing-scheduler-token']);
    await db.exec(`INSERT INTO cron.job (jobname, schedule, command)
      VALUES ('company-news-hourly', '0 0 * * *', 'SELECT 2');`);
    const before = (await db.query<{ jobid: number }>("SELECT jobid FROM cron.job WHERE jobname = 'company-news-hourly'")).rows[0].jobid;
    await db.exec(migration);
    expect((await db.query('SELECT name, secret FROM vault.secrets')).rows).toEqual([
      { name: 'company_news_cron_token', secret: 'existing-scheduler-token' },
    ]);
    expect((await db.query("SELECT jobid, schedule FROM cron.job WHERE jobname = 'company-news-hourly'")).rows)
      .toEqual([{ jobid: before, schedule: '17 * * * *' }]);
    expect((await db.query("SELECT command FROM cron.job WHERE jobname = 'daily-report-cleanup'")).rows)
      .toEqual([{ command: 'SELECT 1' }]);
  });

  it('executes a syntactically valid job using a runtime Vault lookup and an empty worker dispatch body', async () => {
    await db.exec(migration);
    const command = (await db.query<{ command: string }>("SELECT command FROM cron.job WHERE jobname = 'company-news-hourly'")).rows[0].command;
    await db.exec(command);
    const request = (await db.query<{ url: string; headers: Record<string, string>; body: unknown; timeout_milliseconds: number }>('SELECT url, headers, body, timeout_milliseconds FROM net.requests')).rows[0];
    const token = (await db.query<{ secret: string }>("SELECT secret FROM vault.secrets WHERE name = 'company_news_cron_token'")).rows[0].secret;
    expect(request).toEqual({
      url: 'https://ymwrlclbovmipkwgvqgw.supabase.co/functions/v1/company-news',
      headers: { 'Content-Type': 'application/json', 'x-company-news-token': token },
      body: {}, timeout_milliseconds: 10000,
    });
    await db.exec("UPDATE vault.secrets SET secret = 'rotated-token' WHERE name = 'company_news_cron_token'");
    await db.exec(command);
    expect((await db.query<{ headers: Record<string, string> }>('SELECT headers FROM net.requests ORDER BY id DESC LIMIT 1')).rows[0].headers)
      .toEqual({ 'Content-Type': 'application/json', 'x-company-news-token': 'rotated-token' });
  });

  it('does not expose the private scheduler token to browser roles', async () => {
    await db.exec(migration);
    for (const role of ['anon', 'authenticated']) {
      await db.exec(`SET ROLE ${role}`);
      await expect(db.query('SELECT decrypted_secret FROM vault.decrypted_secrets'))
        .rejects.toMatchObject({ code: '42501' });
      await db.exec('RESET ROLE');
    }
  });

  it('fails closed without the public gateway credential, leaving existing jobs untouched', async () => {
    await db.exec(migration);
    const before = (await db.query('SELECT * FROM cron.job ORDER BY jobid')).rows;
    await expect(db.exec(gatewayMigration)).rejects.toMatchObject({ code: 'P0001' });
    await db.exec('ROLLBACK');
    expect((await db.query('SELECT * FROM cron.job ORDER BY jobid')).rows).toEqual(before);
  });

  it('uses a public JWT for gateway headers while keeping scheduler authentication separate', async () => {
    await db.exec(migration);
    await db.query('INSERT INTO vault.secrets (name, secret) VALUES ($1, $2)',
      ['company_news_gateway_key', 'public-project-anon-jwt']);
    await db.exec(gatewayMigration);
    const job = (await db.query<{ command: string; active: boolean }>(
      "SELECT command, active FROM cron.job WHERE jobname = 'company-news-hourly'",
    )).rows[0];
    expect(job.active).toBe(false);
    await db.exec(job.command);
    const headers = (await db.query<{ headers: Record<string, string> }>('SELECT headers FROM net.requests')).rows[0].headers;
    const schedulerToken = (await db.query<{ secret: string }>(
      "SELECT secret FROM vault.secrets WHERE name = 'company_news_cron_token'",
    )).rows[0].secret;
    expect(headers).toEqual({
      'Content-Type': 'application/json',
      apikey: 'public-project-anon-jwt',
      Authorization: 'Bearer public-project-anon-jwt',
      'x-company-news-token': schedulerToken,
    });
    expect(headers['x-company-news-token']).not.toBe(headers.apikey);
    expect(headers.Authorization).not.toContain(schedulerToken);
    expect(job.command).not.toContain(schedulerToken);
    expect(job.command).not.toContain('public-project-anon-jwt');
    expect((await db.query("SELECT command, active FROM cron.job WHERE jobname = 'daily-report-cleanup'")).rows)
      .toEqual([{ command: 'SELECT 1', active: true }]);
  });

  it('keeps the updated job paused and both credentials unchanged when reapplied', async () => {
    await db.exec(migration);
    await db.query('INSERT INTO vault.secrets (name, secret) VALUES ($1, $2)',
      ['company_news_gateway_key', 'public-project-anon-jwt']);
    await db.exec(gatewayMigration);
    const beforeJobs = (await db.query('SELECT * FROM cron.job ORDER BY jobid')).rows;
    const beforeSecrets = (await db.query('SELECT * FROM vault.secrets ORDER BY name')).rows;
    await db.exec(gatewayMigration);
    expect((await db.query('SELECT * FROM cron.job ORDER BY jobid')).rows).toEqual(beforeJobs);
    expect((await db.query('SELECT * FROM vault.secrets ORDER BY name')).rows).toEqual(beforeSecrets);
    expect((await db.query("SELECT active FROM cron.job WHERE jobname = 'company-news-hourly'")).rows)
      .toEqual([{ active: false }]);
  });
});
